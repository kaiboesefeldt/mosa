package straightway.mosa.client.ui.identityconnected

import straightway.mosa.client.ui.*

import react.RefObject
import straightway.mosa.content.QueryResult
import straightway.mosa.content.complaint.PostComplaintState
import straightway.mosa.message.AdminMessage
import web.html.HTMLButtonElement
import web.html.HTMLDivElement

internal data class IdentityConnectedViewModerationController(
    val isInboxOpen: Boolean,
    val isInboxLoading: Boolean,
    val isInboxAppending: Boolean,
    val visibleInboxEntries: List<AdminMessage>,
    val inboxError: String?,
    val inboxHasMore: Boolean,
    val showSeenInboxEntries: Boolean,
    val hasHiddenSeenInboxEntries: Boolean,
    val seenInboxMessageIds: List<String>,
    val hasReadInboxEntries: Boolean,
    val unreadInboxCount: Int,
    val isComplaintQueueOpen: Boolean,
    val isComplaintQueueLoading: Boolean,
    val isComplaintQueueAppending: Boolean,
    val visibleComplaintQueueEntries: List<ComplaintQueueEntry>,
    val complaintQueueError: String?,
    val complaintQueueHasMore: Boolean,
    val showProcessedComplaintEntries: Boolean,
    val hasHiddenProcessedComplaintEntries: Boolean,
    val openComplaintCount: Int,
    val complaintActionPostId: String?,
    val complaintComposerPostId: String?,
    val complaintComposerText: String,
    val complaintComposerError: String?,
    val isComplaintSubmitting: Boolean,
    val complaintDecisionEntryId: String?,
    val complaintDecisionTargetStatus: PostComplaintState?,
    val complaintDecisionText: String,
    val complaintDecisionError: String?,
    val isComplaintDecisionSubmitting: Boolean,
    val inboxButtonRef: RefObject<HTMLButtonElement>,
    val complaintQueueButtonRef: RefObject<HTMLButtonElement>,
    val inboxPopoverRef: RefObject<HTMLDivElement>,
    val complaintQueuePopoverRef: RefObject<HTMLDivElement>,
    val toggleSeenInboxVisibility: () -> Unit,
    val loadInbox: () -> Unit,
    val closeInbox: () -> Unit,
    val loadMoreInbox: () -> Unit,
    val loadComplaintQueue: () -> Unit,
    val closeComplaintQueue: () -> Unit,
    val toggleProcessedComplaintVisibility: () -> Unit,
    val loadMoreComplaintQueue: () -> Unit,
    val requestPostComplaint: (QueryResult.Entry) -> Unit,
    val setComplaintComposerText: (String) -> Unit,
    val closeComplaintComposer: () -> Unit,
    val submitPostComplaint: () -> Unit,
    val startComplaintDecision: (ComplaintQueueEntry, PostComplaintState) -> Unit,
    val setComplaintDecisionText: (String) -> Unit,
    val closeComplaintDecisionComposer: () -> Unit,
    val submitComplaintDecision: () -> Unit,
)

internal fun buildIdentityConnectedViewModerationController(
    state: IdentityConnectedViewModerationControllerState,
    refs: IdentityConnectedViewModerationControllerRefs,
    callbacks: IdentityConnectedViewModerationControllerCallbacks,
): IdentityConnectedViewModerationController =
    IdentityConnectedViewModerationController(
        isInboxOpen = state.isInboxOpen,
        isInboxLoading = state.isInboxLoading,
        isInboxAppending = state.isInboxAppending,
        visibleInboxEntries = state.inboxEntries.filteredForInbox(state.showSeenInboxEntries, state.hiddenSeenInboxMessageIds),
        inboxError = state.inboxError,
        inboxHasMore = state.inboxHasMore,
        showSeenInboxEntries = state.showSeenInboxEntries,
        hasHiddenSeenInboxEntries = state.hiddenSeenInboxMessageIds.isNotEmpty(),
        seenInboxMessageIds = state.seenInboxMessageIds,
        hasReadInboxEntries = state.seenInboxMessageIds.isNotEmpty(),
        unreadInboxCount = state.unreadInboxCount,
        isComplaintQueueOpen = state.isComplaintQueueOpen,
        isComplaintQueueLoading = state.isComplaintQueueLoading,
        isComplaintQueueAppending = state.isComplaintQueueAppending,
        visibleComplaintQueueEntries = state.complaintQueueEntries.filteredForComplaintQueue(state.showProcessedComplaintEntries),
        complaintQueueError = state.complaintQueueError,
        complaintQueueHasMore = state.complaintQueueHasMore,
        showProcessedComplaintEntries = state.showProcessedComplaintEntries,
        hasHiddenProcessedComplaintEntries = state.complaintQueueEntries.any { !it.isOpen() },
        openComplaintCount = state.openComplaintCount,
        complaintActionPostId = state.complaintActionPostId,
        complaintComposerPostId = state.complaintComposerPostId,
        complaintComposerText = state.complaintComposerText,
        complaintComposerError = state.complaintComposerError,
        isComplaintSubmitting = state.isComplaintSubmitting,
        complaintDecisionEntryId = state.complaintDecisionEntryId,
        complaintDecisionTargetStatus = state.complaintDecisionTargetStatus,
        complaintDecisionText = state.complaintDecisionText,
        complaintDecisionError = state.complaintDecisionError,
        isComplaintDecisionSubmitting = state.isComplaintDecisionSubmitting,
        inboxButtonRef = refs.inboxButtonRef,
        complaintQueueButtonRef = refs.complaintQueueButtonRef,
        inboxPopoverRef = refs.inboxPopoverRef,
        complaintQueuePopoverRef = refs.complaintQueuePopoverRef,
        toggleSeenInboxVisibility = callbacks.toggleSeenInboxVisibility,
        loadInbox = callbacks.actions.loadInbox,
        closeInbox = callbacks.actions.closeInbox,
        loadMoreInbox = callbacks.actions.loadMoreInbox,
        loadComplaintQueue = callbacks.actions.loadComplaintQueue,
        closeComplaintQueue = callbacks.actions.closeComplaintQueue,
        toggleProcessedComplaintVisibility = callbacks.actions.toggleProcessedComplaintVisibility,
        loadMoreComplaintQueue = callbacks.actions.loadMoreComplaintQueue,
        requestPostComplaint = callbacks.actions.requestPostComplaint,
        setComplaintComposerText = callbacks.actions.setComplaintComposerText,
        closeComplaintComposer = callbacks.actions.closeComplaintComposer,
        submitPostComplaint = callbacks.actions.submitPostComplaint,
        startComplaintDecision = callbacks.actions.startComplaintDecision,
        setComplaintDecisionText = callbacks.actions.setComplaintDecisionText,
        closeComplaintDecisionComposer = callbacks.actions.closeComplaintDecisionComposer,
        submitComplaintDecision = callbacks.actions.submitComplaintDecision,
    )
