    closeReplyComposer: () -> Unit,
    sendReply: () -> Unit,
    clearTopicFilter: (Topic) -> Unit,
    toggleTopicFilter: (Topic, QueryResult.Entry) -> Unit,
    loadMorePosts: () -> Unit,
    loadMoreReplies: () -> Unit,
