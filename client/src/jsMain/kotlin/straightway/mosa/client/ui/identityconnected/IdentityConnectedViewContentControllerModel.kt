package straightway.mosa.client.ui.identityconnected

import straightway.mosa.client.ui.*

import straightway.mosa.client.content.ThreadReplies
import straightway.mosa.client.content.Topic
import straightway.mosa.client.content.TopicPosts
import straightway.mosa.content.QueryResult

internal data class IdentityConnectedViewContentController(
    val topics: List<Topic>,
    val selectedTopic: Topic?,
    val posts: List<TopicPosts>,
    val selectedPost: QueryResult.Entry?,
    val replies: ThreadReplies?,
    val isLoadingReplies: Boolean,
    val topicFilters: Map<String, Float>,
    val isLoadingPosts: Boolean,
    val isComposerOpen: Boolean,
    val composerText: String,
    val isPublishing: Boolean,
    val publishError: String?,
    val deleteCandidate: QueryResult.Entry?,
    val isDeletingPost: Boolean,
    val isDeletingAllPosts: Boolean,
    val deleteError: String?,
    val isReplyComposerOpen: Boolean,
    val replyComposerText: String,
    val isReplyPublishing: Boolean,
    val replyPublishError: String?,
    val setComposerText: (String) -> Unit,
    val setReplyComposerText: (String) -> Unit,
    val addTopic: () -> Unit,
    val removeTopic: (Topic) -> Unit,
    val selectTopic: (Topic?) -> Unit,
    val openComposer: () -> Unit,
    val closeComposer: () -> Unit,
    val sendPost: () -> Unit,
    val requestDelete: (QueryResult.Entry) -> Unit,
    val clearDeleteCandidate: () -> Unit,
    val confirmDelete: (QueryResult.Entry) -> Unit,
    val deleteAllPosts: () -> Unit,
    val openReplyComposer: () -> Unit,
    val closeReplyComposer: () -> Unit,
    val sendReply: () -> Unit,
    val clearTopicFilter: (Topic) -> Unit,
    val toggleTopicFilter: (Topic, QueryResult.Entry) -> Unit,
    val loadMorePosts: () -> Unit,
    val loadMoreReplies: () -> Unit,
    val selectPost: (QueryResult.Entry) -> Unit,
    val clearReplies: () -> Unit,
    val findTopicByTitle: (String?) -> Topic?,
    val findPostById: (String?) -> QueryResult.Entry?,
)

internal fun buildIdentityConnectedViewContentController(
    state: IdentityConnectedViewContentControllerState,
    actions: IdentityConnectedViewContentControllerActions,
    lookups: IdentityConnectedViewContentControllerLookups,
): IdentityConnectedViewContentController =
    IdentityConnectedViewContentController(
        topics = state.topics,
        selectedTopic = state.selectedTopic,
        posts = state.posts,
        selectedPost = state.selectedPost,
        replies = state.replies,
        isLoadingReplies = state.isLoadingReplies,
        topicFilters = state.topicFilters,
        isLoadingPosts = state.isLoadingPosts,
        isComposerOpen = state.isComposerOpen,
        composerText = state.composerText,
        isPublishing = state.isPublishing,
        publishError = state.publishError,
        deleteCandidate = state.deleteCandidate,
        isDeletingPost = state.isDeletingPost,
        isDeletingAllPosts = state.isDeletingAllPosts,
        deleteError = state.deleteError,
        isReplyComposerOpen = state.isReplyComposerOpen,
        replyComposerText = state.replyComposerText,
        isReplyPublishing = state.isReplyPublishing,
        replyPublishError = state.replyPublishError,
        setComposerText = actions.setComposerText,
        setReplyComposerText = actions.setReplyComposerText,
        addTopic = actions.addTopic,
        removeTopic = actions.removeTopic,
        selectTopic = actions.selectTopic,
        openComposer = actions.openComposer,
        closeComposer = actions.closeComposer,
        sendPost = actions.sendPost,
        requestDelete = actions.requestDelete,
        clearDeleteCandidate = actions.clearDeleteCandidate,
        confirmDelete = actions.confirmDelete,
        deleteAllPosts = actions.deleteAllPosts,
        openReplyComposer = actions.openReplyComposer,
        closeReplyComposer = actions.closeReplyComposer,
        sendReply = actions.sendReply,
        clearTopicFilter = actions.clearTopicFilter,
        toggleTopicFilter = actions.toggleTopicFilter,
        loadMorePosts = actions.loadMorePosts,
        loadMoreReplies = actions.loadMoreReplies,
        selectPost = actions.selectPost,
        clearReplies = actions.clearReplies,
        findTopicByTitle = lookups.findTopicByTitle,
        findPostById = lookups.findPostById,
    )
