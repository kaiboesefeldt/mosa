package straightway.mosa.client.ui

import react.RefObject
import straightway.mosa.content.complaint.PostComplaintState
import straightway.mosa.content.QueryResult
import straightway.mosa.message.AdminMessage
import web.html.HTMLButtonElement
import web.html.HTMLDivElement

internal data class IdentityConnectedViewModerationController(
    val isInboxOpen: Boolean,
    val isInboxLoading: Boolean,
    val isInboxAppending: Boolean,
    val visibleInboxEntries: List<AdminMessage>,
    val inboxError: String?,
    val inboxHasMore: Boolean,
    val showSeenInboxEntries: Boolean,
    val hasHiddenSeenInboxEntries: Boolean,
    val seenInboxMessageIds: List<String>,
    val hasReadInboxEntries: Boolean,
    val unreadInboxCount: Int,
    val isComplaintQueueOpen: Boolean,
    val isComplaintQueueLoading: Boolean,
    val isComplaintQueueAppending: Boolean,
    val visibleComplaintQueueEntries: List<ComplaintQueueEntry>,
    val complaintQueueError: String?,
    val complaintQueueHasMore: Boolean,
    val showProcessedComplaintEntries: Boolean,
    val hasHiddenProcessedComplaintEntries: Boolean,
    val openComplaintCount: Int,
    val complaintActionPostId: String?,
    val complaintComposerPostId: String?,
    val complaintComposerText: String,
    val complaintComposerError: String?,
    val isComplaintSubmitting: Boolean,
    val complaintDecisionEntryId: String?,
    val complaintDecisionTargetStatus: PostComplaintState?,
    val complaintDecisionText: String,
    val complaintDecisionError: String?,
    val isComplaintDecisionSubmitting: Boolean,
    val inboxButtonRef: RefObject<HTMLButtonElement>,
    val complaintQueueButtonRef: RefObject<HTMLButtonElement>,
    val inboxPopoverRef: RefObject<HTMLDivElement>,
    val complaintQueuePopoverRef: RefObject<HTMLDivElement>,
    val toggleSeenInboxVisibility: () -> Unit,
    val loadInbox: () -> Unit,
    val closeInbox: () -> Unit,
    val loadMoreInbox: () -> Unit,
    val loadComplaintQueue: () -> Unit,
    val closeComplaintQueue: () -> Unit,
    val toggleProcessedComplaintVisibility: () -> Unit,
    val loadMoreComplaintQueue: () -> Unit,
    val requestPostComplaint: (QueryResult.Entry) -> Unit,
    val setComplaintComposerText: (String) -> Unit,
    val closeComplaintComposer: () -> Unit,
    val submitPostComplaint: () -> Unit,
    val startComplaintDecision: (ComplaintQueueEntry, PostComplaintState) -> Unit,
    val setComplaintDecisionText: (String) -> Unit,
    val closeComplaintDecisionComposer: () -> Unit,
    val submitComplaintDecision: () -> Unit,
)

internal fun buildIdentityConnectedViewModerationController(
    isInboxOpen: Boolean,
    isInboxLoading: Boolean,
    isInboxAppending: Boolean,
    inboxEntries: List<AdminMessage>,
    showSeenInboxEntries: Boolean,
    hiddenSeenInboxMessageIds: List<String>,
    inboxError: String?,
    inboxHasMore: Boolean,
    seenInboxMessageIds: List<String>,
    unreadInboxCount: Int,
    isComplaintQueueOpen: Boolean,
    isComplaintQueueLoading: Boolean,
    isComplaintQueueAppending: Boolean,
    complaintQueueEntries: List<ComplaintQueueEntry>,
    complaintQueueError: String?,
    complaintQueueHasMore: Boolean,
    showProcessedComplaintEntries: Boolean,
    openComplaintCount: Int,
    complaintActionPostId: String?,
    complaintComposerPostId: String?,
    complaintComposerText: String,
    complaintComposerError: String?,
    isComplaintSubmitting: Boolean,
    complaintDecisionEntryId: String?,
    complaintDecisionTargetStatus: PostComplaintState?,
    complaintDecisionText: String,
    complaintDecisionError: String?,
    isComplaintDecisionSubmitting: Boolean,
    inboxButtonRef: RefObject<HTMLButtonElement>,
    complaintQueueButtonRef: RefObject<HTMLButtonElement>,
    inboxPopoverRef: RefObject<HTMLDivElement>,
    complaintQueuePopoverRef: RefObject<HTMLDivElement>,
    toggleSeenInboxVisibility: () -> Unit,
    actions: IdentityConnectedViewModerationActions,
): IdentityConnectedViewModerationController =
    IdentityConnectedViewModerationController(
        isInboxOpen = isInboxOpen,
        isInboxLoading = isInboxLoading,
        isInboxAppending = isInboxAppending,
        visibleInboxEntries = inboxEntries.filteredForInbox(showSeenInboxEntries, hiddenSeenInboxMessageIds),
        inboxError = inboxError,
        inboxHasMore = inboxHasMore,
        showSeenInboxEntries = showSeenInboxEntries,
        hasHiddenSeenInboxEntries = hiddenSeenInboxMessageIds.isNotEmpty(),
        seenInboxMessageIds = seenInboxMessageIds,
        hasReadInboxEntries = seenInboxMessageIds.isNotEmpty(),
        unreadInboxCount = unreadInboxCount,
        isComplaintQueueOpen = isComplaintQueueOpen,
        isComplaintQueueLoading = isComplaintQueueLoading,
        isComplaintQueueAppending = isComplaintQueueAppending,
        visibleComplaintQueueEntries = complaintQueueEntries.filteredForComplaintQueue(showProcessedComplaintEntries),
        complaintQueueError = complaintQueueError,
        complaintQueueHasMore = complaintQueueHasMore,
        showProcessedComplaintEntries = showProcessedComplaintEntries,
        hasHiddenProcessedComplaintEntries = complaintQueueEntries.any { !it.isOpen() },
        openComplaintCount = openComplaintCount,
        complaintActionPostId = complaintActionPostId,
        complaintComposerPostId = complaintComposerPostId,
        complaintComposerText = complaintComposerText,
        complaintComposerError = complaintComposerError,
        isComplaintSubmitting = isComplaintSubmitting,
        complaintDecisionEntryId = complaintDecisionEntryId,
        complaintDecisionTargetStatus = complaintDecisionTargetStatus,
        complaintDecisionText = complaintDecisionText,
        complaintDecisionError = complaintDecisionError,
        isComplaintDecisionSubmitting = isComplaintDecisionSubmitting,
        inboxButtonRef = inboxButtonRef,
        complaintQueueButtonRef = complaintQueueButtonRef,
        inboxPopoverRef = inboxPopoverRef,
        complaintQueuePopoverRef = complaintQueuePopoverRef,
        toggleSeenInboxVisibility = toggleSeenInboxVisibility,
        loadInbox = actions.loadInbox,
        closeInbox = actions.closeInbox,
        loadMoreInbox = actions.loadMoreInbox,
        loadComplaintQueue = actions.loadComplaintQueue,
        closeComplaintQueue = actions.closeComplaintQueue,
        toggleProcessedComplaintVisibility = actions.toggleProcessedComplaintVisibility,
        loadMoreComplaintQueue = actions.loadMoreComplaintQueue,
        requestPostComplaint = actions.requestPostComplaint,
        setComplaintComposerText = actions.setComplaintComposerText,
        closeComplaintComposer = actions.closeComplaintComposer,
        submitPostComplaint = actions.submitPostComplaint,
        startComplaintDecision = actions.startComplaintDecision,
        setComplaintDecisionText = actions.setComplaintDecisionText,
        closeComplaintDecisionComposer = actions.closeComplaintDecisionComposer,
        submitComplaintDecision = actions.submitComplaintDecision,
    )
